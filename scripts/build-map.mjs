// Generates src/content/world-map.generated.ts: a simplified world basemap (Natural Earth 110m land, public
// domain) plus the Voyage route arcs, projected to SVG path strings. Runs at build time only; the site ships
// no mapping library. Usage: npm run build:map
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath, geoGraticule } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = JSON.parse(await readFile(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topology, topology.objects.land);
const data = JSON.parse(await readFile(new URL('../src/content/voyage-stops.json', import.meta.url), 'utf8'));

const W = 1000;
const H = 560;
const PAD = 14;

// Frame the area the route covers (US east coast to Hong Kong, Zambia to Greece), with breathing room.
const view = geoGraticule().extent([[-102, -44], [134, 62]]).outline();
const projection = geoNaturalEarth1().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], view).clipExtent([[0, 0], [W, H]]);
// Whole-pixel precision is plenty for a basemap shown at <= ~700px wide (error < 0.5px) and keeps the path small.
const path = geoPath(projection).digits(0);

const round = (n) => Math.round(n * 10) / 10;
const pt = (s) => {
  const [x, y] = projection([s.lon, s.lat]);
  return { x: round(x), y: round(y) };
};

const stops = Object.fromEntries(data.stops.map((s) => [s.id, pt(s)]));
const hk = pt(data.lane.to);

/** Quadratic arc between two points, bowed to one side. `bow` > 0 bows north/west first, < 0 south/east. */
function arc(a, b, bow) {
  const dx = b.x - a.x;
  const dy = b.y - a.y;
  const len = Math.hypot(dx, dy) || 1;
  let nx = -dy / len;
  let ny = dx / len;
  // Prefer bowing toward the top of the map for positive bow.
  if (ny > 0 || (Math.abs(ny) < 0.05 && nx > 0)) {
    nx = -nx;
    ny = -ny;
  }
  const off = Math.min(len * 0.22, 130) * bow;
  const cx = round((a.x + b.x) / 2 + nx * off);
  const cy = round((a.y + b.y) / 2 + ny * off);
  return `M${a.x} ${a.y}Q${cx} ${cy} ${b.x} ${b.y}`;
}

const ids = data.stops.map((s) => s.id);
const legs = ids.slice(0, -1).map((id, i) => arc(stops[id], stops[ids[i + 1]], 1));
const lane = arc(stops[data.lane.from], hk, -1);

const out = `// GENERATED by scripts/build-map.mjs. Do not edit by hand. Natural Earth land (public domain).
export const WORLD_MAP = {
  width: ${W},
  height: ${H},
  land: ${JSON.stringify(path(land))},
  graticule: ${JSON.stringify(path(geoGraticule().step([20, 20])()))},
  stops: ${JSON.stringify(stops)},
  legs: ${JSON.stringify(legs)},
  lane: ${JSON.stringify(lane)},
  laneEnd: ${JSON.stringify(hk)},
} as const;
`;
await writeFile(new URL('../src/content/world-map.generated.ts', import.meta.url), out);
console.log(`world-map.generated.ts: ${(out.length / 1024).toFixed(1)} KB, land path ${(path(land).length / 1024).toFixed(1)} KB`);
console.log('stops:', stops);
console.log('legs:', legs.length);
